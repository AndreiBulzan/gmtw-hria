#!/usr/bin/env python3
"""What is actually in the repair corpus, counted from the manifests.

The manuscript's corpus description does not add up, and three separate
numbers in it cannot be reconciled by a reader:

  tracks     The three tracks are given as 1,200 / 750 / 1,050 = 3,000, but the
             corpus is 4,000 records. The missing 1,000 are the English slice,
             and the text leaves them homeless. They are not a fourth track:
             every record in english_structured.jsonl carries track "A". The
             English slice IS Track A, in English, over the same
             JSONSchemaBench schemas. So Track A is 2,200 records of which
             1,200 are Romanian, and the manuscript's "Track A: 1,200" is
             counting half of Track A.

  languages  The text calls English "a quarter of the corpus" in one place and
             describes a "70/30 Romanian/English mixture" in another. Only the
             first is right. 1,000 of 4,000 is 25%, and 75/25 is what every
             manifest says. The 70/30 figure is the design range from the
             original plan ("20-30% English"), not the mixture that shipped.

  6,576      The contamination audit reports this denominator with no
             explanation of what it counts. It is every record in the six
             source files, the whole generated pool, not the 4,000 sampled into
             the mix. The audit therefore sweeps 64% more material than the
             training run ever saw, which is the stronger claim, but only if
             the number is explained.

Also emitted, because the review asks separately for it: each ablation's
replacement policy. The corpus budget is fixed at 4,000 records, so removing a
track does not shrink the corpus -- it raises every surviving track's exposure.
An ablation arm therefore differs from the full recipe in two ways at once, and
the table reports the proportional-rescale reference so a reader can see which
arms are a clean rescale and which were rounded to tidy weights.

Language is declared on Track A records only (meta.language). Track B and
Track C have no such field; they are Romanian by construction, generated by
Romanian-only pipelines. Reported as declared rather than inferred.

  python datagen/analysis/corpus_accounting.py \
      --corpus datagen/data/sft --out datagen/results/tables
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
import pathlib

CORPUS_FILES = ["track_a.jsonl", "track_b_invoice.jsonl", "track_b_contract.jsonl",
                "track_b_anunt.jsonl", "track_c.jsonl", "english_structured.jsonl"]
SHIPPED = "train_mix_4k_v2.manifest.json"


def read_jsonl(path: pathlib.Path):
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                yield json.loads(line)


def declared_language(rec: dict) -> str:
    """'ro'/'en' where the record says so, 'ro (by construction)' otherwise.

    Track B and C carry no meta.language. Rather than silently calling them
    Romanian, mark them so the distinction between a declared and an assumed
    language survives into the table.
    """
    lang = rec.get("meta", {}).get("language")
    return lang if lang else "ro (by construction)"


def pool(corpus: pathlib.Path) -> dict:
    """(file, track, language) -> count over every available record."""
    counts: dict = collections.Counter()
    for name in CORPUS_FILES:
        path = corpus / name
        if not path.exists():
            raise SystemExit(f"missing source file: {path}")
        for rec in read_jsonl(path):
            counts[(name, rec.get("track", "?"), declared_language(rec))] += 1
    return counts


def manifest_rows(corpus: pathlib.Path, name: str) -> list[dict]:
    man = json.load(open(corpus / name, encoding="utf-8"))
    rows = []
    for src in man["sources"]:
        rows.append({
            "file": src["path"].split("/")[-1],
            "weight": float(src["weight"]),
            "train": int(src["sampled"]),
            "val": int(src.get("val_sampled", 0)),
            "available": int(src.get("available", 0)),
        })
    return rows, man


def track_of(filename: str, counts: dict) -> str:
    for (f, track, _lang), n in counts.items():
        if f == filename and n:
            return track
    return "?"


def lang_of(filename: str, counts: dict) -> str:
    for (f, _track, lang), n in counts.items():
        if f == filename and n:
            return lang
    return "?"


def write_pool_table(out: pathlib.Path, counts: dict, shipped, man) -> None:
    """Track x language, available vs shipped, with the 6,576 reconciled."""
    by_src = {r["file"]: r for r in shipped}
    rows = []
    for (fname, track, lang), avail in sorted(counts.items()):
        s = by_src.get(fname, {})
        rows.append({
            "file": fname,
            "track": track,
            "language": lang,
            "available": avail,
            "mix_weight": f"{s.get('weight', 0.0):.4f}",
            "train": s.get("train", 0),
            "val": s.get("val", 0),
        })
    tot_avail = sum(r["available"] for r in rows)
    tot_train = sum(r["train"] for r in rows)
    tot_val = sum(r["val"] for r in rows)
    rows.append({"file": "TOTAL", "track": "", "language": "",
                 "available": tot_avail, "mix_weight": "1.0000",
                 "train": tot_train, "val": tot_val})

    # The two aggregations the manuscript gets wrong.
    by_track: dict = collections.Counter()
    by_lang: dict = collections.Counter()
    for r in rows[:-1]:
        by_track[r["track"]] += r["train"]
        by_lang["en" if r["language"] == "en" else "ro"] += r["train"]
    for track, n in sorted(by_track.items()):
        rows.append({"file": f"track {track} (all languages)", "track": track,
                     "language": "", "available": "", "mix_weight": "",
                     "train": n, "val": ""})
    for lang, n in sorted(by_lang.items()):
        rows.append({"file": f"language {lang}", "track": "", "language": lang,
                     "available": "", "mix_weight": f"{n / tot_train:.4f}",
                     "train": n, "val": ""})

    path = out / "60_corpus_accounting.csv"
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["file", "track", "language",
                                           "available", "mix_weight", "train", "val"])
        w.writeheader()
        w.writerows(rows)

    print(f"\n{'file':30} {'tr':3} {'language':22} {'avail':>6} {'weight':>8} {'train':>6} {'val':>4}")
    for r in rows:
        print(f"{r['file']:30} {r['track']:3} {r['language']:22} "
              f"{str(r['available']):>6} {str(r['mix_weight']):>8} "
              f"{str(r['train']):>6} {str(r['val']):>4}")
    print(f"\naudit denominator  = {tot_avail} available records "
          f"(the 6,576 in the contamination audit)")
    print(f"shipped mix        = {tot_train} train + {tot_val} val, seed {man['seed']}")
    print(f"English fraction   = {by_lang['en']}/{tot_train} = "
          f"{100 * by_lang['en'] / tot_train:.1f}%  (not 30%)")
    print(f"wrote {path}")


def write_ablation_table(out: pathlib.Path, corpus: pathlib.Path, counts: dict) -> None:
    """Each arm's weights against the rescale its own policy implies.

    The policy is not a global rescale. The three track ablations pin the
    English slice at 0.25 and redistribute the freed mass across the surviving
    Romanian tracks only -- English is held constant on purpose, so that a drop
    in a Romanian track is not confounded with a change in the bilingual
    balance. The Romanian-only arm is the exception: there English is the
    ablated slice, so the rescale is global over what remains.

    The reweighting arms (trackc45, c40e30, replay25) drop nothing. They are
    chosen design points, so no rescale reference applies and the column is
    left empty rather than filled with a number that means nothing.
    """
    full_rows, _ = manifest_rows(corpus, SHIPPED)
    full = {r["file"]: r["weight"] for r in full_rows}
    english = "english_structured.jsonl"

    arms = sorted(p.name for p in corpus.glob("train_mix_*.manifest.json")
                  if p.name != SHIPPED)
    rows = []
    for arm in arms:
        arm_rows, man = manifest_rows(corpus, arm)
        w = {r["file"]: r["weight"] for r in arm_rows}
        dropped = [f for f, weight in full.items() if weight > 0 and w.get(f, 0.0) == 0.0]
        added = [f for f in w if f not in full]
        pins_english = dropped and english not in dropped

        freed = sum(full[f] for f in dropped)
        survivors = [f for f in full if f not in dropped
                     and not (pins_english and f == english)]
        survivor_total = sum(full[f] for f in survivors)

        worst = 0.0
        for src in arm_rows:
            f, base_w = src["file"], full.get(f := src["file"], 0.0)
            if not dropped or added:
                expect = ""                       # reweighting arm, no reference
            elif f in dropped:
                expect = 0.0
            elif pins_english and f == english:
                expect = base_w                   # pinned by design
            elif survivor_total:
                expect = base_w + freed * base_w / survivor_total
            else:
                expect = ""
            if expect != "":
                worst = max(worst, abs(src["weight"] - expect))
            rows.append({
                "arm": arm.replace("train_mix_", "").replace(".manifest.json", ""),
                "file": f,
                "track": track_of(f, counts) if f in full else "replay",
                "language": lang_of(f, counts) if f in full else "ro",
                "full_weight": f"{base_w:.4f}",
                "arm_weight": f"{src['weight']:.4f}",
                "implied": "" if expect == "" else f"{expect:.4f}",
                "train": src["train"],
                "delta_records": src["train"] - next(
                    (r["train"] for r in full_rows if r["file"] == f), 0),
            })
        rows.append({"arm": arm.replace("train_mix_", "").replace(".manifest.json", ""),
                     "file": "TOTAL", "track": "", "language": "",
                     "full_weight": "1.0000",
                     "arm_weight": f"{sum(r['weight'] for r in arm_rows):.4f}",
                     "implied": "" if not dropped or added else f"max dev {worst:.4f}",
                     "train": man["total"], "delta_records": 0})

    path = out / "61_ablation_replacement.csv"
    with open(path, "w", newline="", encoding="utf-8") as fh:
        wr = csv.DictWriter(fh, fieldnames=["arm", "file", "track", "language",
                                            "full_weight", "arm_weight",
                                            "implied", "train", "delta_records"])
        wr.writeheader()
        wr.writerows(rows)

    print(f"\n{'arm':12} {'file':28} {'full':>7} {'arm':>7} {'implied':>9} {'train':>6} {'delta':>7}")
    last = None
    for r in rows:
        if r["arm"] != last:
            print()
            last = r["arm"]
        flag = ""
        if r["implied"] and not r["implied"].startswith("max") \
                and abs(float(r["implied"]) - float(r["arm_weight"])) > 5e-4:
            flag = "  <- rounded, not an exact rescale"
        print(f"{r['arm']:12} {r['file']:28} {r['full_weight']:>7} "
              f"{r['arm_weight']:>7} {r['implied']:>9} "
              f"{str(r['train']):>6} {r['delta_records']:>+7}{flag}")
    print(f"\nwrote {path}")
    print("weights as stored sum to 1.0000 +/- 0.0001 on the reweighting arms; "
          "the sampler normalises, so the record counts are exact.")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--corpus", required=True, help="directory holding the track jsonl files")
    ap.add_argument("--out", required=True, help="where the CSVs go")
    args = ap.parse_args()

    corpus = pathlib.Path(args.corpus)
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    counts = pool(corpus)
    shipped, man = manifest_rows(corpus, SHIPPED)
    write_pool_table(out, counts, shipped, man)
    write_ablation_table(out, corpus, counts)


if __name__ == "__main__":
    main()
